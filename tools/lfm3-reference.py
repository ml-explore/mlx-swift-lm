#!/usr/bin/env python3
"""Generate Swift FP32 reference values from LiquidAI's original implementation.

Requires torch, transformers==5.22.1 and huggingface_hub.
Run from the repository root: python tools/lfm3-reference.py
The downloaded Python code is pinned and runs on the CPU without model weights.
Weights are generated in sorted parameter-name order, as in LFM3ReferenceTests.
"""

import json
from pathlib import Path
from tempfile import TemporaryDirectory

import torch
from huggingface_hub import snapshot_download
from transformers import AutoConfig, AutoModelForCausalLM

REVISION = "ac2586a34f1a1c03329dbdcdefabd8b6478ddaa7"
OUTPUT = Path(__file__).resolve().parents[1] / "Tests/MLXLMTests/LFM3ReferenceValues.swift"
CONFIG = {
    "model_type": "lfm3", "hidden_size": 8, "intermediate_size": 16,
    "num_hidden_layers": 3, "num_attention_heads": 2, "num_key_value_heads": 1,
    "head_dim": 8, "vocab_size": 16,
    "layer_types": ["conv", "full_attention", "sliding_attention"],
    "sliding_window": 4, "conv_L_cache": 7, "conv_bias": True,
    "norm_eps": 1e-5, "use_sandwich_norm": True, "tie_word_embeddings": True,
    "pad_token_id": 0, "bos_token_id": 1, "eos_token_id": 2,
    "rope_parameters": {
        "full_attention": {
            "rope_type": "default", "rope_theta": 1000000.0, "partial_rotary_factor": 0.5,
        },
        "sliding_attention": {"rope_type": "default", "rope_theta": 10000.0},
    },
}


def main():
    torch.set_num_threads(4)
    torch.manual_seed(7)
    with TemporaryDirectory(prefix="lfm3-reference-") as source:
        snapshot_download(
            "LiquidAI/LFM3-1.7B", revision=REVISION,
            allow_patterns=["config.json", "*.py"], local_dir=source,
        )
        config = AutoConfig.from_pretrained(source, trust_remote_code=True)
        for key, value in CONFIG.items():
            setattr(config, key, value)
        config._attn_implementation = "eager"
        model = AutoModelForCausalLM.from_config(config, trust_remote_code=True).float().eval()
    with torch.no_grad():
        for i, (_name, parameter) in enumerate(sorted(model.named_parameters())):
            values = (torch.arange(parameter.numel()).reshape(parameter.shape) + i * 3) % 17
            parameter.copy_((values.float() - 8) / 32)
            if parameter.ndim == 1 and parameter.numel() == CONFIG["hidden_size"]:
                parameter.add_(1)
    outputs = {}
    handles = []
    for name, module in model.named_modules():
        if name in ["model.embed_tokens", "model.embedding_norm"] or (
            name.startswith("model.layers.") and name.count(".") == 2
        ) or name.endswith((".conv", ".self_attn")) and name.count(".") == 3:
            def hook(_module, _args, result, name=name):
                tensor = result[0] if isinstance(result, tuple) else result
                outputs[name] = tensor.detach().contiguous().clone()
            handles.append(module.register_forward_hook(hook))
    tokens = torch.tensor([(i * 7 + 3) % 16 for i in range(38)]).reshape(2, 19)
    with torch.no_grad():
        outputs["logits"] = model(tokens, use_cache=False).logits
    for handle in handles:
        handle.remove()
    with torch.no_grad():
        cache = None
        logits = []
        for start, end in [(0, 2), (2, 7), (7, 18), (18, 19)]:
            out = model(tokens[:, start:end], past_key_values=cache, use_cache=True)
            logits.append(out.logits)
            cache = out.past_key_values
        error = (torch.cat(logits, dim=1) - outputs["logits"]).abs().max().item()
    assert error < 2e-5, f"Reference cached/uncached mismatch: {error}"
    # Hashed parameters and sample positions follow @ykhrustalev's review of PR #750.
    hashed_config = CONFIG | {
        "hidden_size": 32, "intermediate_size": 48, "num_hidden_layers": 6,
        "num_attention_heads": 4, "num_key_value_heads": 2, "head_dim": 16,
        "vocab_size": 64, "conv_L_cache": 3, "conv_bias": False,
        "layer_types": ["conv", "sliding_attention", "full_attention"] * 2,
    }
    hashed_config = type(config)(**hashed_config)
    hashed_config._attn_implementation = "eager"
    hashed_model = type(model)(hashed_config).float().eval()
    start = 0
    with torch.no_grad():
        for _name, parameter in sorted(hashed_model.named_parameters()):
            indices = torch.arange(start, start + parameter.numel(), dtype=torch.int64)
            u = (indices * 2654435761 % (1 << 32)).double() / 4294967296 - 0.5
            values = 1 + u if parameter.ndim == 1 else u / 2
            parameter.copy_(values.float().reshape(parameter.shape))
            start += parameter.numel()
        hashed_tokens = torch.tensor([(i * 7 + 3) % 64 for i in range(19)]).reshape(1, 19)
        hashed_logits = hashed_model(hashed_tokens, use_cache=False).logits
    lines = [
        "// Generated by tools/lfm3-reference.py; do not edit values by hand.",
        f"// LiquidAI/LFM3-1.7B {REVISION}; PyTorch CPU FP32, transformers 5.22.1.",
        "", "enum LFM3ReferenceValues {", '    static let configuration = """',
        *["        " + line for line in json.dumps(CONFIG, indent=2).splitlines()],
        '        """', "", "    static let outputs: [String: [Float]] = [",
    ]
    for name, tensor in sorted(outputs.items()):
        lines.append(f'        "{name}": [')
        values = tensor.flatten().tolist()
        for offset in range(0, len(values), 5):
            lines.append("            " + ", ".join(f"{value:.9e}" for value in values[offset:offset+5]) + ",")
        lines.append("        ],")
    lines.extend(["    ]", "", "    static let hashedLogits: [Int: [Float]] = ["])
    for position in [3, 10, 18]:
        values = hashed_logits[0, position, :8].tolist()
        lines.append(f"        {position}: [")
        for offset in range(0, len(values), 5):
            lines.append("            " + ", ".join(f"{value:.9e}" for value in values[offset:offset+5]) + ",")
        lines.append("        ],")
    lines.extend(["    ]", "}", ""])
    OUTPUT.write_text("\n".join(lines))
    print(f"Reference cached/uncached maximum absolute error: {error:.9g}")
    print(f"Wrote {OUTPUT} ({sum(t.numel() for t in outputs.values())} reference values)")


if __name__ == "__main__":
    main()
