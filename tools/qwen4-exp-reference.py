#!/usr/bin/env python3
"""Generate Swift FP32 reference values from mlx-lm's qwen4_exp (Qwen3.8-Flash-Next).

Needs an mlx-lm checkout at the commit below. Run from the repository root:
    uv run --python 3.12 --with-editable ../mlx-lm python tools/qwen4-exp-reference.py
Runs on the CPU in float32. Weights are generated in sorted parameter-name order, as in
Qwen4ExpTests.referenceModel().
"""

import json
import math
from pathlib import Path

import mlx.core as mx
from mlx.utils import tree_flatten

from mlx_lm.models import qwen4_exp
from mlx_lm.models.cache import make_prompt_cache

COMMIT = "c4c9c762cc797fd979fc98645f5db5112753bbe9"
OUTPUT = Path(__file__).resolve().parents[1] / "Tests/MLXLMTests/Qwen4ExpReferenceValues.swift"

# The config of mlx-lm's test_qwen4_exp, with a second PLE layer.
CONFIG = {
    "model_type": "qwen4_exp",
    "text_config": {
        "hidden_size": 64, "num_hidden_layers": 4, "num_attention_heads": 4,
        "num_key_value_heads": 2, "head_dim": 32, "vocab_size": 10000, "rms_norm_eps": 1e-6,
        "full_attention_interval": 4, "num_experts": 8, "num_experts_per_tok": 2,
        "moe_intermediate_size": 32, "shared_expert_intermediate_size": 32,
        "linear_num_key_heads": 2, "linear_num_value_heads": 4, "linear_key_head_dim": 16,
        "linear_value_head_dim": 16, "linear_conv_kernel_dim": 4, "hc_count": 4,
        "hc_lowrank": 16, "indexer_n_heads": 2, "indexer_kv_heads": 1, "indexer_head_dim": 16,
        "indexer_budget": 8, "indexer_compress_ratio": 4, "ngram_size": 3,
        "heads_per_ngram": 2, "ngram_vocab_size_base": 101, "ple_embed_dim": 128,
        "ple_layer_ids": [1, 2], "eos_token_id": [1, 2],
        "rope_parameters": {"rope_theta": 10000000, "partial_rotary_factor": 0.25},
    },
}

# Past the indexer budget (8), with EOS (1) inside the prompt for the n-gram reset.
TOKENS = [
    [1 if i in (5, 13) else (i * 37 + 11) % 10000 for i in range(22)],
    [1 if i == 2 else (i * 101 + 3) % 10000 for i in range(22)],
]
POSITIONS = [0, 5, 11, 12, 16, 21]
VOCAB_SLICE = 64
PREFILL = 15


def weight(index, shape):
    """Exactly representable values; 1-D `.weight` tensors are norms, centred on 1."""
    count = math.prod(shape)
    values = ((mx.arange(count) * 7 + index * 13) % 97 - 48).astype(mx.float32) / 256
    return values.reshape(shape)


def main():
    mx.set_default_device(mx.cpu)
    model = qwen4_exp.Model(qwen4_exp.ModelArgs.from_dict(CONFIG))
    weights = []
    for i, (name, parameter) in enumerate(sorted(tree_flatten(model.parameters()))):
        value = weight(i, parameter.shape)
        if parameter.ndim == 1 and name.endswith(".weight"):
            value = value + 1
        weights.append((name, value))
    model.load_weights(weights)
    mx.eval(model.parameters())

    tokens = mx.array(TOKENS)
    logits = model(tokens)

    # Prefill then decode, against the full forward.
    cache = make_prompt_cache(model)
    steps = [model(tokens[:, :PREFILL], cache=cache)]
    steps += [model(tokens[:, i : i + 1], cache=cache) for i in range(PREFILL, tokens.shape[1])]
    error = mx.abs(mx.concatenate(steps, axis=1) - logits).max().item()
    assert error < 1e-4, f"Reference cached/uncached mismatch: {error}"

    outputs = {
        "logits": logits[:, POSITIONS, :VOCAB_SLICE],
        "logsumexp": mx.logsumexp(logits, axis=-1),
    }
    constants = {}
    for i, layer in enumerate(model.layers):
        if layer.ple is None:
            continue
        table = layer.ple.ple_embedding
        for name, value in [
            ("layer_multipliers", table._mults),
            ("ngram_heads_vocab_sizes", table._sizes),
            ("ngram_heads_offsets", table._offsets),
        ]:
            constants[f"model.layers.{i}.ple.ple_embedding.{name}"] = value.tolist()

    lines = [
        "// Generated by tools/qwen4-exp-reference.py; do not edit values by hand.",
        f"// mlx-lm {COMMIT}; MLX {mx.__version__} CPU FP32.",
        "",
        "enum Qwen4ExpReferenceValues {",
        '    static let configuration = """',
        *["        " + line for line in json.dumps(CONFIG, indent=2).splitlines()],
        '        """',
        "",
        f"    static let tokens: [[Int32]] = {json.dumps(TOKENS)}",
        f"    static let positions = {json.dumps(POSITIONS)}",
        f"    static let vocabularySlice = {VOCAB_SLICE}",
        f"    static let prefill = {PREFILL}",
        "",
        "    static let ngramConstants: [String: [Int64]] = [",
        *[f'        "{k}": {json.dumps(v)},' for k, v in sorted(constants.items())],
        "    ]",
        "",
        "    static let outputs: [String: [Float]] = [",
    ]
    for name, array in sorted(outputs.items()):
        lines.append(f'        "{name}": [')
        values = array.flatten().tolist()
        for offset in range(0, len(values), 5):
            chunk = values[offset : offset + 5]
            lines.append("            " + ", ".join(f"{v:.9e}" for v in chunk) + ",")
        lines.append("        ],")
    lines.extend(["    ]", "}", ""])
    OUTPUT.write_text("\n".join(lines))
    print(f"Reference cached/uncached maximum absolute error: {error:.9g}")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
