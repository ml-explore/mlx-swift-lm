    func testInvalidPixelGrids() throws {
        let model = try model()
        let pixels = MLXArray.zeros([4, 24])
        XCTAssertThrowsError(try model(pixels, frames: []))
        XCTAssertThrowsError(try model(pixels, frames: [THW(Int.max, 2, 2)]))
