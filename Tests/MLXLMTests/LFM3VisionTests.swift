final class LFM3VisionTests: XCTestCase {
    private func configuration(_ overrides: [String: Any] = [:]) throws -> LFM3VisionConfiguration {
        var values: [String: Any] = [
            "hidden_size": 16, "intermediate_size": 24, "num_attention_heads": 2,
            "num_key_value_heads": 1, "patch_size": 2, "temporal_patch_size": 2,
            "spatial_merge_size": 2, "in_channels": 3, "conv_kernel_size": 3,
            "norm_eps": 1e-5, "layer_types": ["conv", "full_attention"],
            "num_hidden_layers": 2,
            "rope_parameters": ["rope_type": "axial", "rope_theta": 1_000_000],
        ]
        values.merge(overrides) { _, new in new }
        return try JSONDecoder().decode(
            LFM3VisionConfiguration.self,
            from: JSONSerialization.data(withJSONObject: values))
    }

    private func model() throws -> LFM3VisionModel {
        let model = LFM3VisionModel(try configuration())
        let weights = model.parameters().flattened().sorted { $0.0 < $1.0 }.enumerated().map {
            index, entry in
            let (key, value) = entry
            let offset = Float(index + 1)
            let weight = sin(MLXArray(0 ..< value.size).asType(.float32) + offset) * 0.1
            return (key, weight.reshaped(value.shape))
        }
        try model.update(parameters: ModuleParameters.unflattened(weights), verify: .all)
        return model
    }

    func testFrameIsolationAndRectangularGrids() throws {
        let model = try model()
        let first = sin(MLXArray(0 ..< 192).asType(.float32)).reshaped(8, 24)
        let second = cos(MLXArray(0 ..< 96).asType(.float32)).reshaped(4, 24)
        let a = try model(first, frames: [THW(1, 2, 4)])
        let b = try model(second, frames: [THW(1, 2, 2)])
        let combined = try model(
            concatenated([first, second]), frames: [THW(1, 2, 4), THW(1, 2, 2)])
        XCTAssertEqual(combined.shape, [12, 16])
        XCTAssertLessThan(abs(combined - concatenated([a, b])).max().item(Float.self), 1e-6)
    }

    func testTemporalGroupsRemainIndependent() throws {
        let model = try model()
        let pixels = sin(MLXArray(0 ..< 192).asType(.float32)).reshaped(8, 24)
        let video = try model(pixels, frames: [THW(2, 2, 2)])
        let images = try model(pixels, frames: [THW(1, 2, 2), THW(1, 2, 2)])
        XCTAssertLessThan(abs(video - images).max().item(Float.self), 1e-6)
    }

