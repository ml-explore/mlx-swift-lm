@Suite("MuseGlimmer configuration")
struct MuseGlimmerConfigurationTests {

    /// The real `config.json` from `meta-models/Muse-Glimmer-30B`, trimmed to the
    /// fields the port reads. `layer_types` and `layer_rope_theta` are omitted so
    /// this also exercises the derive path from `__post_init__`.
    static let derivedJSON = """
