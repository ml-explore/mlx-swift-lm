        """

    static func decode(_ json: String) throws -> MuseGlimmerConfiguration {
        try JSONDecoder().decode(MuseGlimmerConfiguration.self, from: Data(json.utf8))
    }

    @Test("derives the 3:1 sliding/full text pattern with a full final layer")
    func derivedTextLayerTypes() throws {
        let config = try Self.decode(Self.derivedJSON).textConfiguration
        #expect(config.layerTypes.count == 52)

        let fullIndices = config.layerTypes.enumerated()
            .filter { $0.element == "full_attention" }.map(\.offset)
        #expect(fullIndices == Array(stride(from: 3, through: 51, by: 4)))
        #expect(fullIndices.count == 13)
        #expect(config.layerTypes[51] == "full_attention")
        #expect(config.layerTypes[0 ..< 3].allSatisfy { $0 == "sliding_attention" })
    }

    @Test("full-attention layers derive theta 0, i.e. NoPE")
    func derivedLayerRopeTheta() throws {
        let config = try Self.decode(Self.derivedJSON).textConfiguration
        #expect(config.layerRopeTheta.count == 52)
        #expect(config.layerRopeTheta[0] == 500_000)
        #expect(config.layerRopeTheta[3] == 0)
        #expect(config.layerRopeTheta[51] == 0)
        for (index, theta) in config.layerRopeTheta.enumerated() {
            #expect((theta == 0) == (config.layerTypes[index] == "full_attention"))
        }
    }

    @Test("derives 37 window / 13 full vision layers, last layer full")
    func derivedVisionLayerTypes() throws {
        let config = try Self.decode(Self.derivedJSON).visionConfiguration
        #expect(config.layerTypes.count == 50)

        let fullIndices = config.layerTypes.enumerated()
            .filter { $0.element == "full_attention" }.map(\.offset)
        #expect(fullIndices == Array(stride(from: 3, through: 47, by: 4)) + [49])
        #expect(fullIndices.count == 13)
        #expect(config.layerTypes.filter { $0 == "window_attention" }.count == 37)
    }

    @Test("carries the non-default scalars the model depends on")
    func scalars() throws {
        let config = try Self.decode(Self.derivedJSON)
        #expect(config.textConfiguration.qkScaleFactor == 3.87)
        #expect(config.textConfiguration.postNormEps == 1e-8)
        #expect(config.textConfiguration.rmsNormEps == 1e-5)
        #expect(config.textConfiguration.finalLogitSoftcapping == 20.0)
        #expect(abs(config.textConfiguration.outputMultiplier - 0.196_116_135) < 1e-8)
        #expect(config.textConfiguration.tieWordEmbeddings == false)
        #expect(config.outHiddenSize == 6144)
        #expect(config.projectorHiddenSize == 4096)
        #expect(config.imageTokenId == 200092)
        #expect(config.videoTokenId == 200091)
        #expect(config.visionConfiguration.ropeTheta == 10_000)
        #expect(config.textConfiguration.ropeTheta == 500_000)
    }

    @Test("an explicit layer_types array overrides the derived one")
    func explicitLayerTypes() throws {
        let json = """
            {
              "text_config": {
                "num_hidden_layers": 4,
                "layer_types": [
                  "full_attention", "sliding_attention", "sliding_attention", "full_attention"
                ],
                "layer_rope_theta": [0, 123.0, 123.0, 0]
              },
              "vision_config": { "num_hidden_layers": 2 }
            }
            """
        let config = try Self.decode(json).textConfiguration
        #expect(
            config.layerTypes == [
                "full_attention", "sliding_attention", "sliding_attention", "full_attention",
            ])
        #expect(config.layerRopeTheta == [0, 123.0, 123.0, 0])
    }
}

